// Write the client's copy of the engine's service registry, from the engine's.
//
// The registry is `engine/src/services.rs`. Everything on this side of the seam
// — the typed name union, the dev proxy's route list, the worker's dispatch —
// used to be a separate hand-written list, and the lists had drifted:
// `sefarim` was in three of four registries and missing from the fourth (dead
// citation autocomplete in the offline build, caught by nothing), and the Vite
// proxy carried five of twelve routes, so click-to-jump 404'd under
// `npm run dev` for as long as it had existed.
//
// A generated file cannot drift. `npm test` runs the --check form, so a service
// added in Rust and not regenerated here is a red test rather than a feature
// that silently does nothing in one of the four builds.
//
// There are two outputs, for the two places that have to agree with the Rust:
// the app's typed table, and the *service worker's* copy of the paths. The
// worker is a separate script served straight out of `public/` — it is not in
// the module graph and cannot import `services.gen.ts` — and it needs the list
// for the same reason the dev proxy does: it must be able to tell an engine
// service from a static asset. It could not, and cached `/inbox`.
//
//   node tools/emit-services.mjs          # rewrite both generated files
//   node tools/emit-services.mjs --check  # fail if either is stale

import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { runAsScript } from "./generated.mjs";
import { facts, ARTEFACT } from "./facts.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const APP = join(here, "..");
const OUT = join(APP, "src", "services.gen.ts");
const SW_OUT = join(APP, "public", "sw-services.gen.js");

/**
 * The registry, as the engine serialised it.
 *
 * This used to be a regex anchored to one `svc("name", Get, "/path", Quick,
 * All, fn)` **per line**, which is why `services.rs` carried a
 * `#[rustfmt::skip]` and a paragraph explaining that its formatting was a build
 * input: rustfmt's `fn_call_width` is 60 and would have broken every row across
 * seven lines, leaving this generator to parse a table of nothing.
 *
 * The skip is gone with the parser. `engine/src/facts.rs` serialises the table,
 * `cargo test --test facts` keeps `engine/facts.gen.json` current, and the rows
 * can now be laid out however reads best — the generated TypeScript is
 * identical either way. The only translation left is vocabulary: the engine
 * says `get`/`post` and `all`/`native`, and `fetch` wants `GET`/`POST`.
 */
function read() {
  const services = facts().services.map((s) => ({
    name: s.name,
    method: s.method.toUpperCase(),
    path: s.path,
    cost: s.cost,
    nativeOnly: s.reach === "native",
  }));
  // An empty table would generate a file that typechecks, breaks every call at
  // runtime, and looks like a successful regeneration. A truncated artefact
  // lands here.
  if (services.length < 2) {
    console.error(
      `read ${services.length} services out of ${ARTEFACT}\n` +
        "Regenerate it with:\n  KSAV_BLESS=1 cargo test --test facts   (in ksav/engine)",
    );
    process.exit(1);
  }
  return services;
}

/**
 * The operations the one `git` service answers.
 *
 * A single service with an `op` field means the *operation name* is the wire,
 * and a client with its own list of them is the arrangement this whole file
 * exists to have removed — one level down and with the same failure mode. The
 * same emptiness guard applies for the same reason, with one addition: the wasm
 * build does not link `git` at all, so a `facts.gen.json` blessed from it would
 * carry an empty list and generate a client that can ask for nothing.
 */
function readGitOps() {
  const ops = facts().git_ops ?? [];
  if (ops.length < 2) {
    console.error(
      `read ${ops.length} git operations out of ${ARTEFACT}\n` +
        "Bless it from a native build:\n" +
        "  KSAV_BLESS=1 cargo test --test facts   (in ksav/engine)",
    );
    process.exit(1);
  }
  return ops;
}

function emit(services, gitOps) {
  const q = (s) => JSON.stringify(s);
  const union = services.map((s) => q(s.name)).join(" | ");
  const gitUnion = gitOps.map(q).join(" | ");
  const gitRows = gitOps.map(q).join(", ");
  const rows = services
    .map(
      (s) =>
        `  { name: ${q(s.name)}, method: ${q(s.method)}, path: ${q(s.path)}, ` +
        `cost: ${q(s.cost)}, nativeOnly: ${s.nativeOnly} },`,
    )
    .join("\n");
  return `// Generated by app/tools/emit-services.mjs from engine/facts.gen.json,
// which engine/src/facts.rs serialises out of engine/src/services.rs.
// Do not edit by hand: run \`node tools/emit-services.mjs\`.
// \`npm test\` fails when this file and the engine's registry disagree.
//
// This is the client half of one registry. The engine routes HTTP from the same
// table, the wasm module dispatches its single \`ksav_call\` export from it, and
// the desktop shell's single \`ksav_call\` command looks names up in it — so a
// service reaches all four builds by being added once, in Rust.

/** Every service the engine can be asked for. A typo here is a \`tsc\` error. */
export type ServiceName = ${union};

export interface ServiceDef {
  readonly name: ServiceName;
  /** How the HTTP builds reach it. The wasm and desktop builds call by name. */
  readonly method: "GET" | "POST";
  readonly path: string;
  /** \`layout\` lays the document out — the server caps these and the desktop
   *  app runs them off the UI thread. See \`Cost\` in engine/src/services.rs. */
  readonly cost: "layout" | "work" | "quick";
  /** Needs the loopback to Girsa, which a browser tab has no way to reach. */
  readonly nativeOnly: boolean;
}

export const SERVICES: readonly ServiceDef[] = [
${rows}
];

/** The path each service answers on, for the two builds that speak HTTP. */
export const SERVICE_PATH: Readonly<Record<ServiceName, string>> = Object.fromEntries(
  SERVICES.map((s) => [s.name, s.path]),
) as Record<ServiceName, string>;

/**
 * The whole definition, by name — which is what an HTTP caller actually needs.
 *
 * \`SERVICE_PATH\` alone was half the answer, and the missing half cost a working
 * feature: \`api.ts\` took the path from here and the *verb* from which of its two
 * private helpers a call site happened to use. \`/inbox\` was moved to POST in the
 * engine for a real reason — as a GET it was drainable by
 * \`<img src="http://localhost:7878/inbox">\`, which sends no Origin, so no CORS
 * check anywhere could have refused it — and the client kept asking for it with
 * GET. The server answered 404, the poll swallowed it, and the Girsa handoff was
 * dead on a path where both ends were correct.
 */
export const SERVICE: Readonly<Record<ServiceName, ServiceDef>> = Object.fromEntries(
  SERVICES.map((s) => [s.name, s]),
) as Record<ServiceName, ServiceDef>;

/**
 * Every operation the \`git\` service answers.
 *
 * \`git\` is one service carrying an \`op\`, so this is the same registry idea one
 * level down: the engine's \`OPERATIONS\` in \`engine/src/git.rs\` is the list, and
 * a button wired to an operation that is not in it is a \`tsc\` error instead of
 * a refusal shown to a writer.
 */
export type GitOp = ${gitUnion};

export const GIT_OPS: readonly GitOp[] = [${gitRows}];
`;
}

/** The worker's half: the paths, and nothing else it has no use for. */
function emitWorker(services) {
  const rows = services.map((s) => `  ${JSON.stringify(s.path)},`).join("\n");
  return `// Generated by app/tools/emit-services.mjs from engine/facts.gen.json,
// which engine/src/facts.rs serialises out of engine/src/services.rs.
// Do not edit by hand: run \`node tools/emit-services.mjs\`.
// \`npm test\` fails when this file and the engine's registry disagree.
//
// The service worker's copy of the registry — paths only, because refusing to
// cache one is the only question the worker asks about it. Served out of
// \`public/\` rather than bundled, which is why this is a second generated file
// and not an import of \`services.gen.ts\`: \`sw.js\` is not in the module graph.
//
// See \`sw-cache.js\` for what this is for. In short: the worker used to cache
// every same-origin GET, \`/inbox\` is a draining queue polled once a second, and
// the first arrival cached was the same arrival inserted forever.

export const SERVICE_PATHS = [
${rows}
];
`;
}

const services = read();
const built = emit(services, readGitOps());
const builtWorker = emitWorker(services);

/** Every generated output, as `[path, wanted, label]`. */
export const OUTPUTS = [
  [OUT, built, "src/services.gen.ts"],
  [SW_OUT, builtWorker, "public/sw-services.gen.js"],
];

runAsScript(import.meta.url, OUTPUTS, "services", "node tools/emit-services.mjs");
