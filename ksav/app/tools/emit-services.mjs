// Write the client's copy of the engine's service registry, from the engine's.
//
// The registry is `engine/src/services.rs`. Everything on this side of the seam
// — the typed name union, the dev proxy's route list, the worker's dispatch —
// used to be a separate hand-written list, and the lists had drifted:
// `sefarim` was in three of four registries and missing from the fourth (dead
// citation autocomplete in the offline build, caught by nothing), and the Vite
// proxy carried five of twelve routes, so click-to-jump 404'd under
// `npm run dev` for as long as it had existed.
//
// A generated file cannot drift. `npm test` runs the --check form, so a service
// added in Rust and not regenerated here is a red test rather than a feature
// that silently does nothing in one of the four builds.
//
// There are two outputs, for the two places that have to agree with the Rust:
// the app's typed table, and the *service worker's* copy of the paths. The
// worker is a separate script served straight out of `public/` — it is not in
// the module graph and cannot import `services.gen.ts` — and it needs the list
// for the same reason the dev proxy does: it must be able to tell an engine
// service from a static asset. It could not, and cached `/inbox`.
//
//   node tools/emit-services.mjs          # rewrite both generated files
//   node tools/emit-services.mjs --check  # fail if either is stale

import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const APP = join(here, "..");
const SOURCE = join(APP, "..", "engine", "src", "services.rs");
const OUT = join(APP, "src", "services.gen.ts");
const SW_OUT = join(APP, "public", "sw-services.gen.js");

/** One `svc(…)` line of the table, which is the shape that file promises. */
const ENTRY =
  /^\s*svc\("([a-z_]+)",\s*(Get|Post),\s*"([^"]+)",\s*(Layout|Work|Quick),\s*(All|Native),/;

function read() {
  const rust = readFileSync(SOURCE, "utf8");
  const table = rust.slice(rust.indexOf("pub const SERVICES"));
  const services = [];
  for (const line of table.split(/\r?\n/)) {
    if (line.startsWith("]")) break;
    const m = ENTRY.exec(line);
    if (m) {
      services.push({
        name: m[1],
        method: m[2] === "Get" ? "GET" : "POST",
        path: m[3],
        cost: m[4].toLowerCase(),
        nativeOnly: m[5] === "Native",
      });
    }
  }
  // An empty table would generate a file that typechecks, breaks every call at
  // runtime, and looks like a successful regeneration. If the Rust table is ever
  // reformatted past this parser, say so here rather than there.
  if (services.length < 2) {
    console.error(
      `parsed ${services.length} services out of ${SOURCE}\n` +
        "The table is expected to be one `svc(\"name\", Method, \"/path\", Cost, Reach, fn)` per line.",
    );
    process.exit(1);
  }
  return services;
}

function emit(services) {
  const q = (s) => JSON.stringify(s);
  const union = services.map((s) => q(s.name)).join(" | ");
  const rows = services
    .map(
      (s) =>
        `  { name: ${q(s.name)}, method: ${q(s.method)}, path: ${q(s.path)}, ` +
        `cost: ${q(s.cost)}, nativeOnly: ${s.nativeOnly} },`,
    )
    .join("\n");
  return `// Generated by app/tools/emit-services.mjs from engine/src/services.rs.
// Do not edit by hand: run \`node tools/emit-services.mjs\`.
// \`npm test\` fails when this file and the engine's registry disagree.
//
// This is the client half of one registry. The engine routes HTTP from the same
// table, the wasm module dispatches its single \`ksav_call\` export from it, and
// the desktop shell's single \`ksav_call\` command looks names up in it — so a
// service reaches all four builds by being added once, in Rust.

/** Every service the engine can be asked for. A typo here is a \`tsc\` error. */
export type ServiceName = ${union};

export interface ServiceDef {
  readonly name: ServiceName;
  /** How the HTTP builds reach it. The wasm and desktop builds call by name. */
  readonly method: "GET" | "POST";
  readonly path: string;
  /** \`layout\` lays the document out — the server caps these and the desktop
   *  app runs them off the UI thread. See \`Cost\` in engine/src/services.rs. */
  readonly cost: "layout" | "work" | "quick";
  /** Needs the loopback to Girsa, which a browser tab has no way to reach. */
  readonly nativeOnly: boolean;
}

export const SERVICES: readonly ServiceDef[] = [
${rows}
];

/** The path each service answers on, for the two builds that speak HTTP. */
export const SERVICE_PATH: Readonly<Record<ServiceName, string>> = Object.fromEntries(
  SERVICES.map((s) => [s.name, s.path]),
) as Record<ServiceName, string>;
`;
}

/** The worker's half: the paths, and nothing else it has no use for. */
function emitWorker(services) {
  const rows = services.map((s) => `  ${JSON.stringify(s.path)},`).join("\n");
  return `// Generated by app/tools/emit-services.mjs from engine/src/services.rs.
// Do not edit by hand: run \`node tools/emit-services.mjs\`.
// \`npm test\` fails when this file and the engine's registry disagree.
//
// The service worker's copy of the registry — paths only, because refusing to
// cache one is the only question the worker asks about it. Served out of
// \`public/\` rather than bundled, which is why this is a second generated file
// and not an import of \`services.gen.ts\`: \`sw.js\` is not in the module graph.
//
// See \`sw-cache.js\` for what this is for. In short: the worker used to cache
// every same-origin GET, \`/inbox\` is a draining queue polled once a second, and
// the first arrival cached was the same arrival inserted forever.

export const SERVICE_PATHS = [
${rows}
];
`;
}

const services = read();
const built = emit(services);
const builtWorker = emitWorker(services);

/** Every generated output, as `[path, wanted]`. */
const OUTPUTS = [
  [OUT, built, "src/services.gen.ts"],
  [SW_OUT, builtWorker, "public/sw-services.gen.js"],
];

if (process.argv.includes("--check")) {
  for (const [file, wanted, name] of OUTPUTS) {
    let have = null;
    try {
      have = readFileSync(file, "utf8");
    } catch {
      /* missing counts as stale */
    }
    if (have !== wanted) {
      console.error(
        `${name} is stale — the engine's service registry changed and this copy did not.\n` +
          "Run: node tools/emit-services.mjs",
      );
      process.exit(1);
    }
  }
  console.log("services up to date");
} else {
  for (const [file, wanted] of OUTPUTS) {
    writeFileSync(file, wanted);
    console.log("wrote " + file);
  }
}
