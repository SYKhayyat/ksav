// Copy the Tabler icons the shell uses into `src/icons.gen.ts`.
//
// Usage:  node tools/icons.mjs          rewrite
//         node tools/icons.mjs --check  fail if stale (run by `test/run.mjs`)
//
// The names are read off the `icons:begin … icons:end` block of `src/icons.ts`,
// so adding an icon is one line there and one run of this. Only those icons are
// copied, never the set: 5,000 icons in a bundle to draw 120 of them is the icon
// font this replaces. The drawing is Tabler's node list, not markup, so
// `icons.ts` builds each `<svg>` with `createElementNS` and nothing is parsed.

import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { APP, SRC } from "./paths.mjs";
import { runAsScript } from "./generated.mjs";

const OUT = path.join(SRC, "icons.gen.ts");
const require = createRequire(import.meta.url);
const pkg = path.dirname(require.resolve("@tabler/icons/package.json", { paths: [APP] }));
const nodes = JSON.parse(readFileSync(path.join(pkg, "tabler-nodes-outline.json"), "utf8"));
const version = JSON.parse(readFileSync(path.join(pkg, "package.json"), "utf8")).version;

const src = readFileSync(path.join(SRC, "icons.ts"), "utf8");
const block = src.slice(src.indexOf("// icons:begin"), src.indexOf("// icons:end"));
// The values: `: "name"` in the tables. Keys are bare or quoted action ids, which
// never contain a colon-space before a quote.
const names = [...new Set([...block.matchAll(/:\s*"([a-z0-9-]+)"/g)].map((m) => m[1]))].sort();

const missing = names.filter((n) => !nodes[n]);
if (missing.length) {
  console.error(`not in @tabler/icons ${version}: ${missing.join(", ")}`);
  process.exit(1);
}

const body = names
  .map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(nodes[n].map(([tag, a]) => [tag, a]))},`)
  .join("\n");

const built = `// GENERATED by tools/icons.mjs from @tabler/icons ${version} — do not edit.
//
// Tabler Icons, https://tabler.io/icons — MIT License, Copyright (c) 2020-2026 Paweł Kuna.
// Permission is hereby granted, free of charge, to any person obtaining a copy of
// this software and associated documentation files (the "Software"), to deal in the
// Software without restriction, including without limitation the rights to use,
// copy, modify, merge, publish, distribute, sublicense, and/or sell copies of the
// Software, and to permit persons to whom the Software is furnished to do so,
// subject to the following conditions: The above copyright notice and this
// permission notice shall be included in all copies or substantial portions of the
// Software. THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND.

export const TABLER: Readonly<Record<string, readonly (readonly [string, Readonly<Record<string, string>>])[]>> = {
${body}
};
`;

export const OUTPUTS = [[OUT, built, "tabler icons"]];

runAsScript(import.meta.url, OUTPUTS, "tabler icons", "node tools/icons.mjs");
