// The client's copy of the engine's SVG vocabulary, from the measurement.
//
//   cargo run --example emit-svg-vocabulary      # in ksav/engine
//   node tools/emit-svg-vocabulary.mjs
//   node tools/emit-svg-vocabulary.mjs --check   # fail if it is stale
//
// # Why this is generated and not typed
//
// `svgsafe.ts` filters every page of every preview through an allow-list before
// it reaches `innerHTML` (issue #53: a string from the engine was assigned to
// `innerHTML` with no sanitizer at all). The list has to be the truth about **what
// Typst's SVG exporter emits**, and that is a measurement, not an opinion:
//
//   - a hand-written list is a reading of one SVG file, and it goes stale silently
//     — a name the exporter stopped emitting costs nothing, and a name it started
//     emitting drops silently out of every page;
//   - `a` is in the measurement and would not be in a hand-written list. Typst
//     emits an `<a>` with a transparent `<rect>` and no `href` for a link's hit
//     area, so an allow-list written from a reading of the markup and missing it
//     loses **every link in every document**, with nothing to notice.
//
// The denied list is **not** generated: refusing a name is a judgement about
// safety, and a measurement cannot make it. It is typed in `svgsafe.ts`, and
// `engine/tests/svg_output.rs` asserts that the two never disagree about a name
// the engine actually emits — which is the only disagreement with a consequence.

import { readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { runAsScript } from "./generated.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const APP = join(here, "..");
const FIXTURE = join(APP, "..", "engine", "tests", "fixtures", "svg-vocabulary.json");
const OUT = join(APP, "src", "svg-vocabulary.gen.ts");

const v = JSON.parse(readFileSync(FIXTURE, "utf8"));

// The floors, and the refusals, because a truncated fixture generates a
// TypeScript file that typechecks and filters everything away — a blank preview
// pane, reported as a successful build.
for (const [what, rows, least] of [
  ["elements", v.elements, 8],
  ["attributes", v.attributes, 15],
]) {
  if (!Array.isArray(rows) || rows.length < least) {
    console.error(
      `${FIXTURE} lists ${Array.isArray(rows) ? rows.length : "no"} ${what}, expected at least ${least}.\n` +
        "Regenerate with:\n  cd ksav/engine && cargo run --example emit-svg-vocabulary",
    );
    process.exit(1);
  }
}
if (!Array.isArray(v.alarming) || v.alarming.length) {
  console.error(
    `svg-vocabulary.json lists ${JSON.stringify(v.alarming)} under "alarming".\n` +
      "The engine is emitting something that reads as a payload, and the allow-list " +
      "must not be regenerated over it. Read the engine's output before running this again.",
  );
  process.exit(1);
}
if (!v.elements.includes("a")) {
  console.error(
    'svg-vocabulary.json does not list <a>.\n' +
      "Typst emits an <a> for a link's hit area, so a vocabulary without it drops every " +
      "link in every document. If the exporter really stopped emitting it, that is worth " +
      "knowing — but it is worth knowing in a decision, not by re-running a generator.",
  );
  process.exit(1);
}

const q = (s) => JSON.stringify(s);
const rows = (list) => list.map((n) => `  ${q(n)},`).join("\n");

const built = `// Generated by app/tools/emit-svg-vocabulary.mjs from
// engine/tests/fixtures/svg-vocabulary.json — every template compiled by
// engine/examples/emit-svg-vocabulary.rs, every page scanned.
//
// Do not edit by hand: run \`node tools/emit-svg-vocabulary.mjs\`. \`npm test\`
// fails when this file and the measurement disagree.

/**
 * Every element name in a page of engine SVG, measured.
 *
 * \`a\` is here because Typst emits an \`<a>\` with a transparent \`<rect>\` and no
 * \`href\` of its own for a link's hit area. It is the one name on this list that
 * nobody would have written down, and its absence would have dropped every link
 * in every document silently.
 */
export const SVG_ELEMENTS: readonly string[] = [
${rows(v.elements)}
];

/**
 * Every attribute name in a page of engine SVG, measured.
 *
 * \`xmlns\`, \`xmlns:xlink\` and \`xmlns:h5\` because the exporter writes them on
 * every root and a document without its namespace declaration is not an SVG
 * document. \`overflow\` because Typst writes it to clip page content to the media
 * box, and dropping it changes what a page *looks* like rather than what it
 * contains — which is a quieter failure than a missing element.
 */
export const SVG_ATTRIBUTES: readonly string[] = [
${rows(v.attributes)}
];
`;

export const OUTPUTS = [[OUT, built, "svg vocabulary"]];

runAsScript(import.meta.url, OUTPUTS, "svg vocabulary", "node tools/emit-svg-vocabulary.mjs");
