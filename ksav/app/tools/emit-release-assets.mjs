// The engine binaries a release attaches, named once.
//
// # The finding
//
// A person could not install the Emacs package, and underneath that a person
// could not get a `ksav` binary at all. `release.yml` built four desktop
// installers and nothing else, and the desktop shell links the engine as a
// *library* — so installing Ksav put no `ksav` program anywhere on the machine.
// `editors/emacs/README.md` said to run `cargo build --release`, which is a
// compile of the whole Typst compiler, offered to somebody whose stated
// toolchain is Emacs.
//
// So a release attaches the engine itself, per platform. Two files then have to
// agree about what those attachments are called: the workflow that uploads them
// and the Emacs command that downloads them. That is the fifth instance of the
// shape `services.rs` opens by counting — a table written twice, drifting
// silently — and the answer here is the answer there. The table lives in this
// file, the workflow reads it as its build matrix, and the elisp is generated
// from it.
//
//   node tools/emit-release-assets.mjs           # rewrite the elisp
//   node tools/emit-release-assets.mjs --check   # fail if stale
//   node tools/emit-release-assets.mjs --matrix  # the workflow's build matrix
//
// # Bare binaries, not archives
//
// Each asset is the executable itself, not a `.zip` or a `.tar.gz`. It costs
// download size — the engine statically links the Typst compiler — and it buys
// two things worth more than the bytes. The Emacs command needs `url-copy-file`
// and a `chmod`, with no archive tool shelled out to and no extraction path to
// get wrong on one of three platforms. And somebody who is not using Emacs at
// all gets a single file they can run, which is the complaint `release.yml`
// opens with.

import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { runAsScript, isMain } from "./generated.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, "..", "..", "editors", "emacs", "ksav-release.el");

/**
 * Every platform a release carries the engine for.
 *
 * `system` and `arch` are how *Emacs* names this machine, not how Rust or
 * GitHub name it, because the client is the side that has to recognise itself:
 * `system-type` is a symbol (`windows-nt`, `darwin`, `gnu/linux`) and the
 * architecture is the first field of `system-configuration`. Carrying Rust's
 * triple in the same row is what lets one table drive the build as well.
 *
 * The four rows are the four the desktop installers cover, and
 * `app/test/emacs.test.mjs` fails if those two lists ever stop matching — a
 * platform that can install the application and cannot get an engine is exactly
 * the gap this table was added to close, and it would reopen as a quiet one.
 */
export const TARGETS = [
  {
    id: "windows-x86_64",
    runner: "windows-latest",
    triple: "x86_64-pc-windows-msvc",
    system: "windows-nt",
    arch: ["x86_64"],
    built: "ksav.exe",
  },
  {
    id: "linux-x86_64",
    runner: "ubuntu-22.04",
    triple: "x86_64-unknown-linux-gnu",
    system: "gnu/linux",
    arch: ["x86_64"],
    built: "ksav",
  },
  {
    id: "macos-aarch64",
    runner: "macos-latest",
    triple: "aarch64-apple-darwin",
    system: "darwin",
    // Two spellings, because Emacs' configure triple for Apple Silicon is not
    // one thing: a build from source reports `aarch64-apple-darwin` and some
    // packaged builds report `arm64-apple-darwin`. Recognising one of them
    // would send half of the Macs Ksav is most likely to be used on down the
    // "no engine is published for this machine" path, which is the one message
    // here that is meant to be believed.
    arch: ["aarch64", "arm64"],
    built: "ksav",
  },
  {
    id: "macos-x86_64",
    runner: "macos-latest",
    triple: "x86_64-apple-darwin",
    system: "darwin",
    arch: ["x86_64"],
    built: "ksav",
  },
];

/** What the asset is called on the release page. */
export const assetName = (t) => `ksav-engine-${t.id}${t.system === "windows-nt" ? ".exe" : ""}`;

/** Where the binary a person downloads should be saved, on their machine. */
export const installedName = (t) => (t.system === "windows-nt" ? "ksav.exe" : "ksav");

/** The build matrix, as `release.yml` consumes it through `fromJSON`. */
export function matrix() {
  return TARGETS.map((t) => ({
    id: t.id,
    runner: t.runner,
    triple: t.triple,
    built: t.built,
    asset: assetName(t),
  }));
}

function emit() {
  const rows = TARGETS.map(
    (t) =>
      `    ("${t.id}" ${t.system} (${t.arch.map((a) => `"${a}"`).join(" ")}) ` +
      `"${assetName(t)}" "${installedName(t)}")`,
  ).join("\n");

  return `;;; ksav-release.el --- Where a Ksav engine comes from  -*- lexical-binding: t; -*-

;; Generated by ksav/app/tools/emit-release-assets.mjs, which is also where
;; .github/workflows/release.yml gets its build matrix.
;; Do not edit by hand: run \`node tools/emit-release-assets.mjs' in ksav/app.
;; \`npm test' fails when this file and that table disagree.

;;; Commentary:

;; The engine binaries a Ksav release attaches, and how this machine recognises
;; the one that is for it.  \`ksav-install-engine' in \`ksav.el' is the caller.
;;
;; Generated for the same reason \`ksav-services.el' is.  These names are agreed
;; between a workflow that uploads files and elisp that downloads them, and
;; nothing about a disagreement is visible until somebody's install fails with a
;; 404 — which is precisely the class of silent drift this product has already
;; paid for four times over in four other languages.

;;; Code:

(require 'seq)

(defconst ksav-release-targets
  '(
${rows})
  "Every platform a Ksav release carries an engine for.

Each row is: an identifier, the \`system-type' it is for, the architectures it
answers to as spelt in the first field of \`system-configuration', the asset's
name on the release page, and what the binary should be called once it is on
disk.")

(defun ksav-release-arch ()
  "This machine's architecture, as \`system-configuration' spells it."
  (car (split-string system-configuration "-")))

(defun ksav-release-this-machine ()
  "The row in \`ksav-release-targets' for the machine running this Emacs.

Nil when there is none — a platform Ksav does not publish an engine for is a
real answer, and the caller says so by name rather than downloading something
that cannot run."
  (let ((arch (ksav-release-arch)))
    (seq-find (lambda (row)
                (and (eq system-type (nth 1 row))
                     (member arch (nth 2 row))))
              ksav-release-targets)))

(defun ksav-release-asset (row)
  "The name asset ROW has on the release page."
  (nth 3 row))

(defun ksav-release-binary (row)
  "What the binary in ROW should be called once it is on disk."
  (nth 4 row))

(provide 'ksav-release)
;;; ksav-release.el ends here
`;
}

const built = emit();

export const OUTPUTS = [[OUT, built, "editors/emacs/ksav-release.el"]];

// Before `runAsScript`, which treats any argument that is not `--check` as
// "rewrite the file". The workflow asks this question on every release and must
// not write anything while doing it.
if (isMain(import.meta.url) && process.argv.includes("--matrix")) {
  console.log(JSON.stringify(matrix()));
} else {
  runAsScript(import.meta.url, OUTPUTS, "release assets", "node tools/emit-release-assets.mjs");
}
