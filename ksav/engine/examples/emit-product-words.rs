//! Regenerate `assets/lexicon-he-product.txt`: the words **this product itself
//! writes**, in a layer the checker always has on.
//!
//! The rule the file exists for is one sentence: *any word we write is a word the
//! checker accepts.* It was not true — the welcome document said `וייצוא`, the
//! word on the export menu, and the speller underlined it, because the dictionary
//! is built from Torah and pre-war literature and has no word for "export".
//! Measured over everything the product says, 117 Hebrew tokens were unknown;
//! most were ordinary modern Hebrew, which is a dictionary question the modern
//! half answers, and the rest are this product's own vocabulary.
//!
//! # Why this asks the checker instead of splitting on characters
//!
//! The first draft collected runs of Hebrew letters, and it was wrong in three
//! ways that a hand-written splitter is always wrong in: `ב"ה` and `מהרש"א` came
//! out as fragments (`ב`, `הרש`), because a gershayim inside an abbreviation is
//! not a separator; `אחוזים'` and `נק׳` kept or lost their geresh depending on
//! which character it was; and the list ended up agreeing with *nobody*, since
//! the thing that decides what a word is, is the checker's own tokenizer.
//!
//! So the words here are exactly the tokens `Checker::check` reports against an
//! **empty** lexicon — the checker's tokenizer, the checker's idea of what is
//! checkable, the checker's normalization. Whatever it will look up tomorrow is
//! whatever this file holds, by construction; what the file does *not* have to be
//! is sorted by hand.
//!
//! `tests/product_words.rs` is the other half: it runs the real checker with the
//! real layers over these same sources and fails when this file is stale.
//!
//! Run: `cargo run --example emit-product-words`

use ksav_engine::spell::hebrew::Lexicon;
use ksav_engine::spell::Checker;
use std::io::Write as _;

/// Every text the product puts in front of a writer.
///
/// The Hebrew interface strings, both starter documents, and all twelve
/// templates. Not the documentation: a page of prose is read, not written, and a
/// word that exists only there is a word the writer did not type.
const SOURCES: &[(&str, &str)] = &[
    (
        "app/src/i18n-he.ts",
        include_str!("../../app/src/i18n-he.ts"),
    ),
    (
        "app/src/starter.ts",
        include_str!("../../app/src/starter.ts"),
    ),
    (
        "engine/templates/article-en.ksav",
        include_str!("../templates/article-en.ksav"),
    ),
    (
        "engine/templates/article.ksav",
        include_str!("../templates/article.ksav"),
    ),
    (
        "engine/templates/bentcher.ksav",
        include_str!("../templates/bentcher.ksav"),
    ),
    (
        "engine/templates/divrei-torah.ksav",
        include_str!("../templates/divrei-torah.ksav"),
    ),
    (
        "engine/templates/gemara.ksav",
        include_str!("../templates/gemara.ksav"),
    ),
    (
        "engine/templates/get.ksav",
        include_str!("../templates/get.ksav"),
    ),
    (
        "engine/templates/kesubah.ksav",
        include_str!("../templates/kesubah.ksav"),
    ),
    (
        "engine/templates/letter-en.ksav",
        include_str!("../templates/letter-en.ksav"),
    ),
    (
        "engine/templates/letter.ksav",
        include_str!("../templates/letter.ksav"),
    ),
    (
        "engine/templates/peirush.ksav",
        include_str!("../templates/peirush.ksav"),
    ),
    (
        "engine/templates/sefer.ksav",
        include_str!("../templates/sefer.ksav"),
    ),
    (
        "engine/templates/siddur.ksav",
        include_str!("../templates/siddur.ksav"),
    ),
];

fn main() {
    // An empty lexicon: every token is a miss, which is what makes this a
    // census of the sources rather than a diff against them.
    let empty_he = Lexicon::empty();
    let checker = Checker::new(Some(&empty_he), None);

    let mut words = std::collections::BTreeSet::new();
    for (_, text) in SOURCES {
        for miss in checker.check(text) {
            if miss
                .word
                .chars()
                .any(|c| ('\u{0590}'..='\u{05FF}').contains(&c))
            {
                words.insert(miss.word);
            }
        }
    }
    let out =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("assets/lexicon-he-product.txt");
    let mut f = std::fs::File::create(&out).expect("create the product layer");
    write!(
        f,
        "# Ksav Hebrew lexicon — words this product writes itself. Generated by\n\
         # `cargo run --example emit-product-words` from the interface strings, the two\n\
         # starter documents and the twelve templates. Do not edit by hand: add the word\n\
         # where it is written, then rerun.\n\
         #\n\
         # The list is the checker's own tokenizer run over those sources against an empty\n\
         # dictionary, so it holds exactly the tokens the checker will look up — including\n\
         # `ב\"ה` and `מהרש\"א`, which a hand-written splitter turns into fragments.\n\
         #\n\
         # This layer is **always on**, whatever the writer chooses for the modern and\n\
         # rabbinic halves: the product may not underline its own vocabulary. Words the\n\
         # corpus layers already hold are repeated here on purpose — a product word must\n\
         # not depend on a setting somebody else chose.\n\
         #\n\
         # {} entries, no bands (nothing here is a corpus frequency).\n",
        words.len()
    )
    .expect("write the header");
    for w in &words {
        writeln!(f, "{w}").expect("write a word");
    }
    println!("wrote {} ({} entries)", out.display(), words.len());
}
